const fillBlock = (text, open, close, body) => {
  const from = text.indexOf(open)
  const to = text.indexOf(close)
  if (from === -1 || to === -1) {
    throw new Error(`no generated block in ${FEATURES}`)
  }
  return `${text.slice(0, from + open.length)}\n\n${body}\n\n${text.slice(to)}`
}

await vite.close()

// Formatted here rather than left to `pnpm format`, and that is the difference
// between a check that holds and one that cries wolf: oxfmt reflows markdown,
// so a file this script emitted and a file oxfmt has since touched are not the
// same bytes, and --check would report every clean tree as stale. Generating
// what the formatter would have produced anyway settles it in one place.
//
// Resolved through node rather than spelled as `node_modules/.bin/oxfmt`, which
// is only there in a full checkout: a `git worktree` copy has no node_modules of
// its own, and node's own lookup walks up into the one it shares.
const require = createRequire(import.meta.url)
const oxfmtPkg = require.resolve('oxfmt/package.json')
const OXFMT = join(dirname(oxfmtPkg), require(oxfmtPkg).bin.oxfmt)
const SCRATCH = 'docs/.docgen-scratch.md'
const format = text => {
  writeFileSync(SCRATCH, text)
  try {
    execFileSync(OXFMT, [SCRATCH], { stdio: 'ignore' })
    return readFileSync(SCRATCH, 'utf8')
  } finally {
    rmSync(SCRATCH, { force: true })
  }
}

const pages = [
  { path: LLMS, text: llms },
  { path: LLMS_FULL, text: llmsFull },
  { path: EFFECTS, text: format(effects) },
  {
    path: FEATURES,
    text: format(
      fillBlock(
        readFileSync(FEATURES, 'utf8'),
        LOOPS_OPEN,
        LOOPS_CLOSE,
        loopsBlock,
      ),
    ),
  },
]

if (process.argv.includes('--check')) {
  const stale = pages.filter(p => readFileSync(p.path, 'utf8') !== p.text)
  if (stale.length > 0) {
    console.error(
      `stale — run \`pnpm docgen\`: ${stale.map(p => p.path).join(', ')}`,
    )
    process.exit(1)
  }
  console.log(`current: ${pages.map(p => p.path).join(', ')}`)
} else {
  for (const page of pages) {
    writeFileSync(page.path, page.text)
  }
  const n = GROUPS.reduce((a, g) => a + g.sliders.length, 0)
  console.log(
    `${EFFECTS}: ${GROUPS.length} groups, ${n} controls · ${FEATURES}: ${LOOP_STAGES.length} loops`,
  )
}
