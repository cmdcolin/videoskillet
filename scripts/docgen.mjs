// Checked against the live tables as it is assembled, because a worked example
// is the part a reader copies first and the only part of this page that can be
// wrong in a way nothing else notices — a control renamed under it leaves a link
// that quietly does nothing.
const example = (() => {
  const keys = ['headSwitchShiftUs', 'tintDeg']
  const preset = 'vhs'
  const known = new Set(GROUPS.flatMap(g => g.sliders.map(s => s.key)))
  for (const key of keys) {
    if (!known.has(key)) throw new Error(`${LLMS}: no control ${key}`)
  }
  if (!PRESETS.some(p => p.name === preset)) {
    throw new Error(`${LLMS}: no preset ${preset}`)
  }
  return `https://videoskillet.com/app/#preset=${preset}&set=${keys[0]}:9&mod=${keys[1]}:sine:0.2:0.4`
})()

