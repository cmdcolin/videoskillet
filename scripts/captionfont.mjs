// Draws the caption font in Firefox and writes it to
// src/core/gpu/captionfont.ts, the ROM both caption boxes read. The engine
// ships that file so every platform and the headless renderer get the same
// glyphs; rerun this only to change the font.
//
// Usage: node scripts/captionfont.mjs

import { launchFirefox } from './browser.mjs'

import { writeFileSync } from 'node:fs'

const GLYPH_W = 8
const GLYPH_H = 12
const GLYPH_FIRST = 0x20
const GLYPH_COUNT = 96
const CELL_PX = 11
const INK = 96
const FONT = `${CELL_PX}px "DejaVu Sans Mono", "Liberation Mono", "Courier New", monospace`

const browser = await launchFirefox({ headless: true })
const page = await browser.newPage()
const rows = await page.evaluate(
  (w, h, first, count, font, ink) => {
    const g = new OffscreenCanvas(w, h).getContext('2d')
    g.font = font
    g.textAlign = 'center'
    g.textBaseline = 'middle'
    g.fillStyle = '#fff'
    const out = []
    for (let i = 0; i < count; i++) {
      g.clearRect(0, 0, w, h)
      g.fillText(String.fromCodePoint(first + i), w / 2, h / 2)
      const img = g.getImageData(0, 0, w, h)
      for (let y = 0; y < h; y++) {
        let bits = 0
        for (let x = 0; x < w; x++) {
          if (img.data[(y * w + x) * 4 + 3] >= ink) bits |= 1 << x
        }
        out.push(bits)
      }
    }
    return out
  },
  GLYPH_W,
  GLYPH_H,
  GLYPH_FIRST,
  GLYPH_COUNT,
  FONT,
  INK,
)
await browser.close()

if (rows.length !== GLYPH_COUNT * GLYPH_H || rows.every(r => r === 0)) {
  throw new Error('the browser drew no glyphs')
}

const hex = b => `0x${b.toString(16).padStart(2, '0')}`
const lines = []
for (let i = 0; i < GLYPH_COUNT; i++) {
  const glyph = rows.slice(i * GLYPH_H, (i + 1) * GLYPH_H).map(hex)
  lines.push(
    `  ${glyph.join(', ')}, // ${JSON.stringify(String.fromCodePoint(GLYPH_FIRST + i))}`,
  )
}

const out = new URL('../src/core/gpu/captionfont.ts', import.meta.url)
writeFileSync(
  out,
  `// Generated by scripts/captionfont.mjs from ${CELL_PX}px DejaVu Sans Mono.
// One byte per glyph row, low bit leftmost, glyphs 0x${GLYPH_FIRST.toString(16)}..0x${(GLYPH_FIRST + GLYPH_COUNT - 1).toString(16)}.

// prettier-ignore
export const CAPTION_FONT = new Uint8Array([
${lines.join('\n')}
])
`,
)
console.log('wrote', out.pathname)
